#!/usr/bin/env node
// Writes version-switcher.js, the site script that keeps readers on the same
// page when they switch versions, from the versions in docs.json.
//   node scripts/version-switcher.mjs           # write
//   node scripts/version-switcher.mjs --check   # exit 1 if out of date
// The snapshot and legacy-version scripts run it after changing docs.json.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SWITCHER_FILE = path.join(REPO_ROOT, "version-switcher.js");

function pagesOf(node, acc = []) {
  if (typeof node === "string") acc.push(node);
  else if (Array.isArray(node)) node.forEach((n) => pagesOf(n, acc));
  else if (node && typeof node === "object") for (const k of ["pages", "groups", "tabs", "anchors"]) if (node[k]) pagesOf(node[k], acc);
  return acc;
}

export function versionMap(docs) {
  return docs.navigation.versions.map((v, i) => {
    // The latest version lives at the root; older ones under versions/v<version>/.
    const prefix = i === 0 ? "" : `versions/v${v.version}/`;
    const pages = pagesOf(v).map((p) => {
      if (!p.startsWith(prefix)) throw new Error(`docs.json: ${v.version} page "${p}" is outside ${prefix || "the root"}`);
      return p.slice(prefix.length);
    });
    return { version: v.version, prefix, pages };
  });
}

export function switcherSource(docs) {
  return `// Generated by scripts/version-switcher.mjs from docs.json. Don't edit by hand.
// Mintlify's version switcher opens the first page of the chosen version, because each
// version keeps its pages under its own path. This opens the same page instead, or the
// version's Welcome page if it has no such page.
(() => {
  const VERSIONS = ${JSON.stringify(versionMap(docs))};
  const byVersion = new Map(VERSIONS.map((v) => [v.version, v]));
  const url = (v, page) => "/" + (v.prefix + page).replace(/(^|\\/)index$/, "");

  function currentVersion() {
    const m = location.pathname.match(/^\\/versions\\/v(\\d+\\.\\d+\\.\\d+)(?=\\/|$)/);
    return (m && byVersion.get(m[1])) || VERSIONS[0];
  }

  function onSelect(event) {
    if (event.type === "keydown" && event.key !== "Enter" && event.key !== " ") return;
    const item = event.target instanceof Element && event.target.closest('[role="menuitem"], [role="menuitemradio"], [role="option"]');
    const label = item && item.textContent.trim().match(/^(\\d+\\.\\d+\\.\\d+)(?![\\d.])/);
    const target = label && byVersion.get(label[1]);
    const from = currentVersion();
    if (!target || target === from) return;
    const rel = location.pathname.replace(/^\\/|\\/$/g, "").slice(from.prefix.length) || "index";
    const same = target.pages.includes(rel);
    event.preventDefault();
    event.stopImmediatePropagation();
    location.assign(url(target, same ? rel : "index") + (same ? location.hash : ""));
  }

  window.addEventListener("click", onSelect, true);
  window.addEventListener("keydown", onSelect, true);
})();
`;
}

export async function writeSwitcher(docs) {
  await writeFile(SWITCHER_FILE, switcherSource(docs));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const docs = JSON.parse(await readFile(path.join(REPO_ROOT, "docs.json"), "utf8"));
  if (process.argv.includes("--check")) {
    const current = await readFile(SWITCHER_FILE, "utf8").catch(() => "");
    if (current !== switcherSource(docs)) {
      console.error("version-switcher.js is out of date; run node scripts/version-switcher.mjs");
      process.exit(1);
    }
    console.log("version-switcher.js matches docs.json.");
  } else {
    await writeSwitcher(docs);
    console.log(`Wrote version-switcher.js for ${docs.navigation.versions.length} version(s).`);
  }
}
